/// **Feature: `shadcn`.**
///
/// Re-export of the [`freyacn-shadcn`] crate — pre-built shadcn/ui
/// components and the matching default theme.
///
/// ```rust,no_run
/// # #[cfg(feature = "shadcn")] {
/// extern crate freyacn;
/// use freyacn::prelude::*;
/// use freyacn::shadcn::{Button, Card};
///
/// let ui = Card()
///     .child(text("Welcome"))
///     .child(Button().child(text("Continue")));
/// # }
/// ```
#[cfg(feature = "shadcn")]
#[doc(inline)]
pub use freyacn_shadcn as shadcn;

/// **Feature: `material3`.**
///
/// Re-export of the [`freyacn-material3`] crate — Material Design 3
/// components and the matching default theme. Includes the MD3 tonal
/// palette (`primaryContainer`, `surfaceVariant`, `onSurface`, …) as
/// semantic tokens.
#[cfg(feature = "material3")]
#[doc(inline)]
pub use freyacn_material3 as material3;

